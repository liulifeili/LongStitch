def load():
    out = {}
    for key, rel in FILES.items():
        path = ROOT / rel
        if not path.exists():
            print("文件不存在，整个对账作废：" + rel)
            sys.exit(2)
        out[key] = path.read_text(encoding="utf-8").splitlines()
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quiet", action="store_true", help="只报问题行")
    args = ap.parse_args()

    lines = load()
    bad = 0
    for name, key, needle in EVIDENCE:
        hits = sum(1 for l in lines[key] if needle in l)
        if hits == 0:
            bad += 1
            print("MISSING " + name + "   [在 " + key + " 找不到字面：" + needle + "]")
        elif not args.quiet:
            print("ok      " + name + "   (" + key + " 命中 " + str(hits) + ")")

    absent_bad = 0
    for name, key, needle in MUST_BE_ABSENT:
        hits = sum(1 for l in lines[key] if needle in l)
        if hits != 0:
            absent_bad += 1
            print("FORBIDDEN " + name + "   [在 " + key + " 命中 " + str(hits) + " 次：" + needle + "]")
        elif not args.quiet:
            print("ok-反证  " + name + "   (确实在 " + key + " 找不到)")

    total = len(EVIDENCE) + len(MUST_BE_ABSENT)
    print("")
    print("需求↔证据对账：应存在 " + str(len(EVIDENCE)) + " 行，反证 "
          + str(len(MUST_BE_ABSENT)) + " 行；问题 " + str(bad + absent_bad) + " 行 / 共 "
          + str(total) + " 行。")
    if bad or absent_bad:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
